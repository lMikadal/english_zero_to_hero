// Generates src/lib/srs/scheduler.golden.vectors.ts from ts-fsrs ITSELF (not from our adapter), so the golden test
// compares the adapter against the library.
// Run (Docker only):  docker compose run --rm --no-deps app node scripts/srs-golden.mjs > src/lib/srs/scheduler.golden.vectors.ts
// Re-run it, and read the diff, whenever ts-fsrs is upgraded. The configuration below must equal SRS_CONFIG
// (src/lib/srs/config.ts); a test pins both.
import { DefaultScheduler } from "ts-fsrs";

const CONFIG = {
  version: "FSRS-6",
  desiredRetention: 0.9,
  enableShortTerm: true,
  learningSteps: ["1m", "10m"],
  relearningSteps: ["10m"],
  enableFuzz: false,
  maximumInterval: 36500,
};
const START = new Date("2026-01-01T01:00:00.000Z");
const DAY = 86_400_000;
const EARLY_MS = 8 * 3_600_000;

const SEQUENCES = {
  "good x4, on time": { ratings: [3, 3, 3, 3], early: false },
  "lapse then recover: 1 3 3": { ratings: [1, 3, 3], early: false },
  "easy x2": { ratings: [4, 4], early: false },
  "good, lapse, good, good: 3 1 3 3": { ratings: [3, 1, 3, 3], early: false },
  "hard x2 then good": { ratings: [2, 2, 3], early: false },
  "good x8, on time": { ratings: [3, 3, 3, 3, 3, 3, 3, 3], early: false },
  "good x5, 8 hours early once the interval is 2+ days": { ratings: [3, 3, 3, 3, 3], early: true },
};

const scheduler = await DefaultScheduler(CONFIG);
const out = [];
for (const [name, { ratings, early }] of Object.entries(SEQUENCES)) {
  let card = scheduler.newCard({ now: START });
  const steps = [];
  for (const rating of ratings) {
    const now = early && card.scheduledDays >= 2 ? new Date(card.dueAt.getTime() - EARLY_MS) : new Date(card.dueAt);
    const elapsedDays = card.lastReviewAt ? Math.floor((now.getTime() - card.lastReviewAt.getTime()) / DAY) : 0;
    card = scheduler.review({ card, grade: rating, now }).card;
    steps.push({
      rating,
      now: now.toISOString(),
      due: card.dueAt.toISOString(),
      stability: Number(card.stability.toFixed(4)),
      difficulty: Number(card.difficulty.toFixed(4)),
      state: card.state,
      scheduledDays: card.scheduledDays,
      learningSteps: card.learningStep,
      reps: card.reps,
      lapses: card.lapses,
      elapsedDays,
    });
  }
  out.push({ name, steps });
}
console.log("// GENERATED by scripts/srs-golden.mjs from ts-fsrs. Do not edit by hand; see the script header.");
console.log(`// config: ${JSON.stringify(CONFIG)}; first review at ${START.toISOString()}`);
console.log(`export type GoldenStep = { rating: 1 | 2 | 3 | 4; now: string; due: string; stability: number; difficulty: number; state: 0 | 1 | 2 | 3; scheduledDays: number; learningSteps: number; reps: number; lapses: number; elapsedDays: number };`);
console.log(`export const GOLDEN_START = "${START.toISOString()}";`);
console.log("export const GOLDEN_SEQUENCES: { name: string; steps: GoldenStep[] }[] = [");
for (const { name, steps } of out) {
  console.log(`  {\n    name: ${JSON.stringify(name)},\n    steps: [`);
  for (const s of steps) console.log(`      ${JSON.stringify(s).replace(/"(\w+)":/g, "$1: ").replace(/,/g, ", ").replace(/\{/, "{ ").replace(/\}$/, " }")},`);
  console.log("    ],\n  },");
}
console.log("];");
